using Chatbot.Core.Domain;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NpgsqlTypes;
using Pgvector;

namespace Chatbot.Infrastructure.Knowledge;

/// <summary>
/// One markdown file of a business knowledge base (SPEC 7.6). They live in Infrastructure, not in Core with the rest of the
/// domain, because the vector and tsvector column types come from the Pgvector and Npgsql packages.
/// </summary>
public class KnowledgeDocument
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public Guid BusinessId { get; set; }

    /// <summary>Path relative to the knowledge folder, e.g. <c>dental/cancellation-policy.md</c>. Unique per business.</summary>
    public string SourcePath { get; set; } = "";

    /// <summary>File name without extension: the <c>doc-slug</c> of <c>doc-slug#ordinal</c> source ids.</summary>
    public string Slug { get; set; } = "";

    public string Title { get; set; } = "";

    /// <summary><c>es</c> or <c>en</c>.</summary>
    public string Language { get; set; } = "en";

    public List<string> Tags { get; set; } = [];

    /// <summary>SHA-256 of the normalized content, the embedding model, the dimensions and the chunker: when it matches, ingestion skips the file.</summary>
    public string ContentHash { get; set; } = "";

    /// <summary>The <c>updated</c> date of the frontmatter (the ingestion time if it has none).</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    public List<KnowledgeChunk> Chunks { get; set; } = [];
}

public class KnowledgeChunk
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public Guid DocumentId { get; set; }

    /// <summary>Denormalized from the document: every search filters by it without a join.</summary>
    public Guid BusinessId { get; set; }

    /// <summary>0-based position in the document; with the document slug it forms the source id.</summary>
    public int Ordinal { get; set; }

    public string Heading { get; set; } = "";

    /// <summary>Starts with the <c>Title &gt; Heading</c> context line; it is the text that was embedded.</summary>
    public string Text { get; set; } = "";

    /// <summary>Estimated (4 characters per token).</summary>
    public int TokenCount { get; set; }

    public Vector Embedding { get; set; } = null!;

    /// <summary>The model that produced <see cref="Embedding"/>. Embeddings of different models are never compared.</summary>
    public string EmbeddingModel { get; set; } = "";

    /// <summary>Generated by PostgreSQL from <see cref="Heading"/> and <see cref="Text"/> with the <c>simple</c> configuration. Never assigned.</summary>
    public NpgsqlTsVector SearchVector { get; private set; } = null!;

    public KnowledgeDocument? Document { get; set; }

    /// <summary>The id the model and the trace use to cite this chunk.</summary>
    public static string SourceIdOf(string slug, int ordinal) => $"{slug}#{ordinal}";
}

internal sealed class KnowledgeDocumentConfiguration : IEntityTypeConfiguration<KnowledgeDocument>
{
    public void Configure(EntityTypeBuilder<KnowledgeDocument> b)
    {
        b.ToTable("knowledge_documents");
        b.HasKey(x => x.Id);
        b.Property(x => x.SourcePath).HasMaxLength(300).IsRequired();
        b.Property(x => x.Slug).HasMaxLength(200).IsRequired();
        b.Property(x => x.Title).HasMaxLength(300).IsRequired();
        b.Property(x => x.Language).HasMaxLength(8).IsRequired();
        b.Property(x => x.ContentHash).HasMaxLength(64).IsRequired();
        b.HasOne<Business>().WithMany().HasForeignKey(x => x.BusinessId).OnDelete(DeleteBehavior.Cascade);
        b.HasIndex(x => new { x.BusinessId, x.SourcePath }).IsUnique();
        b.HasIndex(x => new { x.BusinessId, x.Slug }).IsUnique();
    }
}

internal sealed class KnowledgeChunkConfiguration : IEntityTypeConfiguration<KnowledgeChunk>
{
    public void Configure(EntityTypeBuilder<KnowledgeChunk> b)
    {
        b.ToTable("knowledge_chunks");
        b.HasKey(x => x.Id);
        b.Property(x => x.Heading).HasMaxLength(500).IsRequired();
        b.Property(x => x.Text).IsRequired();
        b.Property(x => x.EmbeddingModel).HasMaxLength(200).IsRequired();
        b.Property(x => x.Embedding).HasColumnType($"vector({KnowledgeSchema.EmbeddingDimensions})").IsRequired();
        b.HasOne(x => x.Document).WithMany(d => d.Chunks).HasForeignKey(x => x.DocumentId).OnDelete(DeleteBehavior.Cascade);
        b.HasOne<Business>().WithMany().HasForeignKey(x => x.BusinessId).OnDelete(DeleteBehavior.Cascade);

        // 'simple': no stop words and no stemming, so Spanish and English documents are indexed the same way (ADR-016).
        b.HasGeneratedTsVectorColumn(x => x.SearchVector, "simple", x => new { x.Heading, x.Text });

        b.HasIndex(x => new { x.DocumentId, x.Ordinal }).IsUnique();
        b.HasIndex(x => x.BusinessId);
        b.HasIndex(x => x.SearchVector).HasMethod("GIN");
        b.HasIndex(x => x.Embedding).HasMethod("hnsw").HasOperators("vector_cosine_ops");
    }
}
